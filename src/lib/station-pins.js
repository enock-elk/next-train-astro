function pinLatLon(pair) {
    return { lat: pair[0], lon: pair[1] };
}

/** Config pin for a station name, or null when this stop is not in the dictionary. */
export function canonicalStationPin(name) {
    const raw = String(name || '').replace(/\s+STATION$/i, '').trim().toUpperCase();
    if (!raw) return null;
    if (STATION_PINS[raw]) return pinLatLon(STATION_PINS[raw]);
    const norm = raw.replace(/-/g, ' ').replace(/\s+/g, ' ');
    for (const [key, pair] of Object.entries(STATION_PINS)) {
        const folded = key.replace(/-/g, ' ').replace(/\s+/g, ' ');
        if (folded === norm) return pinLatLon(pair);
    }
    return null;
}
